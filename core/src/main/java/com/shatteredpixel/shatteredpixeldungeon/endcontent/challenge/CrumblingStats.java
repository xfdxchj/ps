	/**
	 * END(1 牢地碎破): 查询某区域内某怪物的数值。
	 *
	 * @param region  区域（1..5）
	 * @param mobName 怪物的**简单类名**
	 * @return 数值；该区域没有为此怪配表则返回 null（保持原版数值）
	 */
	public static Stats lookup(int region, String mobName) {
		Map<String, Stats> m = BY_REGION.get(region);
		return (m == null) ? null : m.get(mobName);
	}

	/** 供诊断用：本表登记的条目总数。 */
	public static int size() {
		int n = 0;
		for (Map<String, Stats> m : BY_REGION.values()) n += m.size();
		return n;
	}
